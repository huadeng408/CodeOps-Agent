# Retrieval evaluation driver for the 180 techdocs qrels (plan Task 3 runner).
#
# Calls the official runner (orchestrator/eval/runner.py) once per named
# retrieval run and writes one redacted JSON report per run:
#   {run} in bm25 / bge_m3 / hybrid_rrf / hybrid_rerank
#   predictions : {PredictionsDir}/{run}-predictions.jsonl
#   report      : {OutputDir}/{run}-report.json
#
# PREREQUISITES — this script does NOT generate predictions and does NOT
# touch any index/alias. Do NOT run it for real until BOTH hold:
#   1. The full corpus import into knowledge_base_v2_bge_m3 has finished.
#      (Evaluating while only pilot data is imported yields pilot-level
#      numbers only and is not the alias-switch gate.)
#   2. The predictions JSONL for each run has been produced by the retrieval
#      system with one hit per line:
#      {"query_id","document_id","section_path","score"}, top-10+ per query).
# Runs whose predictions file is missing are reported as SKIPPED, never
# fabricated. A reranker outage means hybrid_rerank stays skipped/disabled.
#
# Note: orchestrator/eval/runner.py consumes only qrels + predictions. The
# queries file (queries.text.jsonl) is input for the retrieval system that
# generates predictions; here it is only checked for presence.
#
# Usage (from repo root):
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts/eval/run-retrieval-eval.ps1 `
#       -QrelsPath data/eval/techdocs/qrels.text.jsonl `
#       -QueriesPath data/eval/techdocs/queries.text.jsonl `
#       -PredictionsDir results/retrieval `
#       -IndexAlias knowledge_base_current `
#       -CorpusGeneration techdocs-2026-07-30-v1 `
#       -OutputDir results/retrieval

param(
    [string]$QrelsPath = "data/eval/techdocs/qrels.text.jsonl",
    [string]$QueriesPath = "data/eval/techdocs/queries.text.jsonl",
    [string]$PredictionsDir = "results/retrieval",
    [string]$IndexAlias = "knowledge_base_current",
    [string]$CorpusGeneration = "techdocs-2026-07-30-v1",
    [string]$OutputDir = "results/retrieval",
    [string[]]$Runs = @("bm25", "bge_m3", "hybrid_rrf", "hybrid_rerank")
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path "orchestrator/eval/runner.py")) {
    Write-Error "orchestrator/eval/runner.py not found; run this script from the repo root"
    exit 2
}
if (-not (Test-Path $QrelsPath)) {
    Write-Error "qrels file not found: $QrelsPath"
    exit 2
}
if (-not (Test-Path $QueriesPath)) {
    Write-Error "queries file not found: $QueriesPath"
    exit 2
}

New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null

Write-Host "=== Retrieval evaluation (180 techdocs qrels) ==="
Write-Host "  corpus generation : $CorpusGeneration"
Write-Host "  index alias       : $IndexAlias (report metadata only, nothing is written)"
Write-Host "  qrels             : $QrelsPath"
Write-Host "  queries           : $QueriesPath (not consumed by the runner)"
Write-Host "  predictions dir   : $PredictionsDir"
Write-Host "  output dir        : $OutputDir"
Write-Host "  runs              : $($Runs -join ', ')"
Write-Host ""

$results = @()
$exitCode = 0

foreach ($run in $Runs) {
    $predictionsPath = Join-Path $PredictionsDir "$run-predictions.jsonl"
    $reportPath = Join-Path $OutputDir "$run-report.json"

    if (-not (Test-Path $predictionsPath)) {
        Write-Host "[$run] SKIPPED: predictions not found: $predictionsPath"
        Write-Host "       generate it via the retrieval system first (one JSON hit per line, top-10+ per query)"
        $results += [pscustomobject]@{ Run = $run; Status = "SKIPPED"; Report = "-" }
        continue
    }

    Write-Host "[$run] evaluating: $predictionsPath"
    python -m orchestrator.eval.runner `
        --qrels-path $QrelsPath `
        --predictions-path $predictionsPath `
        --corpus-generation $CorpusGeneration `
        --index-alias $IndexAlias `
        --output-path $reportPath `
        --visual-disabled

    if ($LASTEXITCODE -ne 0) {
        Write-Host "[$run] FAILED: runner exit code $LASTEXITCODE"
        $results += [pscustomobject]@{ Run = $run; Status = "FAILED"; Report = "-" }
        $exitCode = 1
    } else {
        Write-Host "[$run] OK: $reportPath"
        $results += [pscustomobject]@{ Run = $run; Status = "OK"; Report = $reportPath }
    }
    Write-Host ""
}

Write-Host "=== Summary ==="
$results | Format-Table -AutoSize | Out-String | Write-Host

$skipped = @($results | Where-Object { $_.Status -eq "SKIPPED" }).Count
if ($skipped -gt 0) {
    Write-Host "$skipped run(s) skipped: predictions must be generated by the retrieval system"
    Write-Host "after the full corpus import completes before the evaluation is meaningful."
}

exit $exitCode
