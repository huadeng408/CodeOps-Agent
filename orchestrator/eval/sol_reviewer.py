def _review_timestamp() -> str:
    """Truncated second-resolution timestamp for deterministic testing."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S+00:00")


def _es_search_url(es_url: str, index: str) -> str:
    base = es_url.rstrip("/")
    return f"{base}/{index}/_search"


def fetch_evidence(
    es_url: str,
    index: str,
    document_id: str,
    section_path: list[str],
    max_chars: int = MAX_EVIDENCE_CHARS_DEFAULT,
) -> list[EvidenceChunk]:
    """Fetch corpus evidence chunks from ES for a qrel document.

    Uses a ``term`` query on ``document_id`` only. *section_path* is kept
    in the signature for API compatibility but intentionally NOT used as an
    ES filter — corpus section_path values are hierarchical while qrel
    section_path values are flat short paths, so filtering by them would
    return zero results. The model judges relevance of retrieved chunks.

    Returns up to *max_chars* total text (individual chunks truncated to
    ``EVIDENCE_CHUNK_TRUNCATE``). Raises RuntimeError on ES failure.
    """
    del section_path  # unused; see docstring above
    must_clauses: list[dict[str, Any]] = [
        {"term": {"document_id": document_id}},
    ]

    payload: dict[str, Any] = {
        "query": {"bool": {"must": must_clauses}},
        "_source": ["text_content", "source_path", "section_path", "document_id"],
        "size": 50,
    }
    data = json.dumps(payload).encode("utf-8")
    url = _es_search_url(es_url, index)
    req = urllib.request.Request(url, data=data, headers={"Content-Type": "application/json"}, method="POST")

    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            body = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:500]
        raise RuntimeError(f"ES search HTTP {exc.code}: {detail}") from exc
    except OSError as exc:
        raise RuntimeError(f"ES connection failed: {exc}") from exc

    hits = body.get("hits", {}).get("hits", []) or []
    chunks: list[EvidenceChunk] = []
    total_chars = 0

    for hit in hits:
        src = hit.get("_source", {}) or {}
        text = str(src.get("text_content", "") or "")
        if not text.strip():
            continue
        truncated = text[:EVIDENCE_CHUNK_TRUNCATE]
        sp = src.get("section_path")
        if isinstance(sp, list):
            section = sp
        else:
            section = []
        chunk = EvidenceChunk(
            document_id=str(src.get("document_id", document_id)),
            section_path=section,
            source_path=str(src.get("source_path", "") or ""),
            text=truncated,
        )
        chunks.append(chunk)
        total_chars += len(truncated)
        if total_chars >= max_chars:
            break

    return chunks


