def arbitrate(
    pass_a: dict[str, PassVerdict],
    pass_b: dict[str, PassVerdict],
    qrels: list[dict[str, Any]],
    confidence_threshold: float = CONFIDENCE_THRESHOLD_DEFAULT,
) -> list[dict[str, Any]]:
    """Deterministically arbitrate two independent review passes.

    Returns one dict per qrel (both passes present) with review_status
    (AI_REVIEWED or DISPUTED) and machine-readable dispute_reason.
    """
    qrel_by_id: dict[str, dict[str, Any]] = {
        str(r["query_id"]): r for r in qrels
    }
    rows: list[dict[str, Any]] = []

    common_ids = set(pass_a) & set(pass_b)
    for qid in sorted(common_ids):
        a = pass_a[qid]
        b = pass_b[qid]
        qrel = qrel_by_id.get(qid, {})

        base: dict[str, Any] = {
            "query_id": qid,
            "document_id": qrel.get("document_id", ""),
            "section_path": qrel.get("section_path", []),
            "relevance": qrel.get("relevance", 0.0),
            "source_id": qrel.get("source_id", ""),
            "language": qrel.get("language", ""),
            "query_type": qrel.get("query_type", ""),
            "pass_a_verdict": {
                "answerable": a.answerable,
                "language_correct": a.language_correct,
                "query_type_correct": a.query_type_correct,
                "relevance_correct": a.relevance_correct,
                "section_correct": a.section_correct,
                "evidence_sufficient": a.evidence_sufficient,
                "contamination_risk": a.contamination_risk,
                "confidence": a.confidence,
            },
            "pass_b_verdict": {
                "answerable": b.answerable,
                "language_correct": b.language_correct,
                "query_type_correct": b.query_type_correct,
                "relevance_correct": b.relevance_correct,
                "section_correct": b.section_correct,
                "evidence_sufficient": b.evidence_sufficient,
                "contamination_risk": b.contamination_risk,
                "confidence": b.confidence,
            },
            "review_prompt_hash": a.prompt_hash,
            "review_evidence": "|".join(a.evidence_refs),
            "review_timestamp": _review_timestamp(),
        }

        # Arbitration logic
        reason: str
        review_status: str
        review_confidence: float = 0.0

        if a.failed or b.failed:
            review_status = "DISPUTED"
            reasons = []
            if a.failed:
                reasons.append(f"{a.fail_reason or 'unknown'}")
            if b.failed:
                reasons.append(f"{b.fail_reason or 'unknown'}")
            reason = f"pass_failed:{'|'.join(reasons)}"
        elif a.fail_reason == "evidence_fetch_failed" or b.fail_reason == "evidence_fetch_failed":
            review_status = "DISPUTED"
            reason = "evidence_missing"
        elif not a.answerable or not b.answerable:
            review_status = "DISPUTED"
            reason = "unanswerable"
        elif (
            a.relevance_correct == b.relevance_correct
            and a.section_correct == b.section_correct
            and a.language_correct == b.language_correct
            and a.query_type_correct == b.query_type_correct
            and a.evidence_sufficient == b.evidence_sufficient
        ):
            # All dimensions agree
            min_conf = min(a.confidence, b.confidence)
            if a.relevance_correct is False and b.relevance_correct is False:
                # Both agree qrel is wrong → still disputed (needs human fix)
                review_status = "DISPUTED"
                reason = "both_reject_qrel"
                review_confidence = round(min_conf, 3)
            elif min_conf >= confidence_threshold:
                review_status = "AI_REVIEWED"
                reason = ""
                review_confidence = round(min_conf, 3)
            else:
                review_status = "DISPUTED"
                reason = "low_confidence"
                review_confidence = round(min_conf, 3)
        else:
            review_status = "DISPUTED"
            reason = "disagreement"
            review_confidence = round(min(a.confidence, b.confidence), 3)

        base["review_status"] = review_status
        base["review_confidence"] = review_confidence
        base["dispute_reason"] = reason
        rows.append(base)

    return rows


def summarize(
    final_rows: list[dict[str, Any]],
    pass_a: dict[str, PassVerdict],
    pass_b: dict[str, PassVerdict],
    meta: dict[str, Any],
) -> dict[str, Any]:
    """Produce a review summary from arbitration results."""
    ai = [r for r in final_rows if r["review_status"] == "AI_REVIEWED"]
    disputed = [r for r in final_rows if r["review_status"] == "DISPUTED"]

    # Count dispute reasons
    reason_counts: dict[str, int] = {}
    for r in disputed:
        reason = r.get("dispute_reason", "unknown")
        reason_counts[reason] = reason_counts.get(reason, 0) + 1

    # Per-source breakdown
    per_source: dict[str, dict[str, int]] = {}
    for r in final_rows:
        src = r.get("source_id", "unknown")
        entry = per_source.setdefault(src, {"total": 0, "AI_REVIEWED": 0, "DISPUTED": 0})
        entry["total"] += 1
        entry[r["review_status"]] += 1

    # Per-language breakdown
    per_language: dict[str, dict[str, int]] = {}
    for r in final_rows:
        lang = r.get("language", "unknown")
        entry = per_language.setdefault(lang, {"total": 0, "AI_REVIEWED": 0, "DISPUTED": 0})
        entry["total"] += 1
        entry[r["review_status"]] += 1

    # Pass-level stats
    pass_a_failed = sum(1 for v in pass_a.values() if v.failed)
    pass_b_failed = sum(1 for v in pass_b.values() if v.failed)

    disputed_qids = [r["query_id"] for r in disputed]

    return {
        "meta": meta,
        "total_queries": len(final_rows),
        "ai_reviewed": len(ai),
        "disputed": len(disputed),
        "dispute_reasons": reason_counts,
        "pass_a_failed": pass_a_failed,
        "pass_b_failed": pass_b_failed,
        "per_source": per_source,
        "per_language": per_language,
        "disputed_query_ids": disputed_qids,
        "ai_reviewed_query_ids": [r["query_id"] for r in ai],
    }


