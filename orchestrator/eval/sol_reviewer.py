@dataclass(frozen=True, slots=True)
class EvidenceChunk:
    """A single chunk of corpus evidence for a qrel document."""

    document_id: str
    section_path: list[str]
    source_path: str
    text: str


@dataclass(frozen=True, slots=True)
class PassVerdict:
    """One independent review pass's judgement for a single query/qrel."""

    query_id: str
    pass_id: str  # "A" | "B"
    failed: bool  # True when this pass could not produce a valid verdict
    fail_reason: str | None  # "llm_error" | "parse_failed" | "evidence_fetch_failed"
    answerable: bool
    language_correct: bool
    query_type_correct: bool
    relevance_correct: bool
    section_correct: bool
    evidence_sufficient: bool
    contamination_risk: str  # "none" | "possible" | "clear"
    confidence: float  # 0.0–1.0; 0.0 when failed
    prompt_hash: str  # sha256 hex[:16]
    evidence_refs: tuple[str, ...]  # "es:<index>:<doc_id>:<source_path>" per chunk


# ---------------------------------------------------------------------------
# Redaction (defence in depth)
