"""GPT-5.6 Sol dual-pass independent AI review of qrels (Phase 3).

Runs two independent review passes (A + B) over every query/qrel pair with
corpus evidence fetched from Elasticsearch, then deterministically arbitrates
the two passes into AI_REVIEWED / DISPUTED statuses.

Key design constraints:
  - Sidecar output — never overwrites the original qrels file.
  - Reviewer hash is NEVER generated by AI — reserved for human reviewers.
  - HUMAN_REVIEWED status is NEVER assigned by AI — only by human workflow.
  - Raw model text is NEVER written to artifacts — only parsed whitelist fields.
  - All outputs pass redact_text() before write (defense in depth).
  - Resume: completed rows (with review_timestamp + parsed verdicts) are skipped.
  - Pass B is information-equivalent to Pass A but with reordered inputs and
    different prompt framing; it never sees Pass A output.
"""

