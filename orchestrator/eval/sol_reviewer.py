# Look for a JSON object (naive brace match) in raw text.
_RE_JSON_BLOCK = re.compile(r"\{[^{}]*(?:\{[^{}]*\}[^{}]*)*\}", re.DOTALL)


def parse_verdict_json(text: str) -> dict[str, Any] | None:
    """Parse model output into a strict verdict dict.

    Tries json.loads on the full text first; falls back to regex extraction
    of the first ``{...}`` block; returns None if both fail.
    """
    stripped = text.strip()
    # Direct parse
    try:
        return json.loads(stripped)
    except json.JSONDecodeError:
        pass

    # Regex fallback
    match = _RE_JSON_BLOCK.search(stripped)
    if match:
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            pass

    return None


_VERDICT_BOOL_KEYS = frozenset({
    "answerable", "language_correct", "query_type_correct",
    "relevance_correct", "section_correct", "evidence_sufficient",
})
_VALID_CONTAMINATION = frozenset({"none", "possible", "clear"})


def validate_verdict_fields(
    d: dict[str, Any],
    query_id: str,
    pass_id: str,
) -> PassVerdict | None:
    """Validate and clamp parsed verdict fields into a PassVerdict.

    Missing keys or wrong types → fail closed (returns None).
    """
    failed = False
    fail_reason: str | None = None

    # Boolean fields
    bools: dict[str, bool] = {}
    for key in sorted(_VERDICT_BOOL_KEYS):
        val = d.get(key)
        if not isinstance(val, bool):
            failed = True
            if fail_reason is None:
                fail_reason = f"bad_field:{key}"
            bools[key] = False
        else:
            bools[key] = val

    # contamination_risk
    risk = str(d.get("contamination_risk", "")).lower().strip()
    if risk not in _VALID_CONTAMINATION:
        risk = "none"

    # confidence — clamp to [0, 1]
    try:
        confidence = float(d.get("confidence", 0.0))
    except (TypeError, ValueError):
        confidence = 0.0
    if not (0.0 <= confidence <= 1.0):
        confidence = max(0.0, min(1.0, confidence))

    return PassVerdict(
        query_id=query_id,
        pass_id=pass_id,
        failed=failed,
        fail_reason=fail_reason,
        answerable=bools["answerable"],
        language_correct=bools["language_correct"],
        query_type_correct=bools["query_type_correct"],
        relevance_correct=bools["relevance_correct"],
        section_correct=bools["section_correct"],
        evidence_sufficient=bools["evidence_sufficient"],
        contamination_risk=risk,
        confidence=confidence,
        prompt_hash="",  # set by caller
        evidence_refs=(),  # set by caller
    )


