def run_review(
    qrels_path: str | Path,
    queries_path: str | Path,
    pass_a_out: str | Path,
    pass_b_out: str | Path,
    arbitrated_out: str | Path,
    summary_path: str | Path,
    es_url: str,
    index: str,
    model: str,
    revision: str,
    confidence_threshold: float = CONFIDENCE_THRESHOLD_DEFAULT,
    resume: bool = True,
    only: str | None = None,
    max_evidence_chars: int = MAX_EVIDENCE_CHARS_DEFAULT,
) -> dict[str, Any]:
    """Run the full Sol dual-pass review pipeline.

    Returns the summary dict; sidecar files are written incrementally.
    """
    qrels = load_qrels(qrels_path)
    queries = load_queries(queries_path)

    client = OpenAIClient.from_env()
    if client is None:
        raise RuntimeError(
            "OpenAIClient.from_env() returned None — "
            "set OPENAI_API_KEY / OPENAI_BASE_URL / OPENAI_MODEL in the environment"
        )
    # Override with explicit args
    if model:
        client.model = model

    meta: dict[str, Any] = {
        "prompt_schema_version": PROMPT_SCHEMA_VERSION,
        "model": model,
        "revision": revision,
        "confidence_threshold": confidence_threshold,
        "es_url": es_url,
        "index": index,
        "qrels_path": str(qrels_path),
        "queries_path": str(queries_path),
        "pass_a_out": str(pass_a_out),
        "pass_b_out": str(pass_b_out),
        "resume": resume,
    }

    pass_a: dict[str, PassVerdict] = {}
    pass_b: dict[str, PassVerdict] = {}

    async def _run() -> None:
        nonlocal pass_a, pass_b
        if only is None or only == "passA":
            print(f"=== PASS A ({len(qrels)} queries) ===")
            pass_a = await run_pass(
                client, "A", qrels, queries, es_url, index,
                str(pass_a_out), model, revision, resume, max_evidence_chars,
            )
        if only is None or only == "passB":
            print(f"=== PASS B ({len(qrels)} queries) ===")
            pass_b = await run_pass(
                client, "B", qrels, queries, es_url, index,
                str(pass_b_out), model, revision, resume, max_evidence_chars,
            )

    asyncio.run(_run())

    # Arbitration (always runs from file contents to support --only arbitrate)
    if only is None or only == "arbitrate":
        # Reload from files (handles --only passA/B followed by --only arbitrate)
        if not pass_a:
            pass_a_src = load_sidecar(str(pass_a_out))
            pass_a = _reconstruct_verdicts(pass_a_src, "A")
        if not pass_b:
            pass_b_src = load_sidecar(str(pass_b_out))
            pass_b = _reconstruct_verdicts(pass_b_src, "B")

        print(f"=== ARBITRATE ({len(pass_a)} A, {len(pass_b)} B) ===")
        final_rows = arbitrate(pass_a, pass_b, qrels, confidence_threshold)

        # Write arbitrated output
        arb_path = Path(arbitrated_out)
        arb_path.parent.mkdir(parents=True, exist_ok=True)
        # Always rewrite — arbitration is deterministic
        with arb_path.open("w", encoding="utf-8") as fh:
            for row in final_rows:
                text = json.dumps(row, ensure_ascii=False)
                text = redact_text(text)
                fh.write(text + "\n")
        print(f"arbitrated: {arb_path} ({len(final_rows)} rows)")

        # Write summary
        summary = summarize(final_rows, pass_a, pass_b, meta)
        sum_path = Path(summary_path)
        sum_path.parent.mkdir(parents=True, exist_ok=True)
        sum_text = json.dumps(summary, indent=2, ensure_ascii=False)
        sum_path.write_text(redact_text(sum_text) + "\n", encoding="utf-8")
        print(f"summary: {sum_path}")

        return summary

    return {"meta": meta, "pass_a_count": len(pass_a), "pass_b_count": len(pass_b)}


def _reconstruct_verdicts(
    sidecar: dict[str, dict[str, Any]],
    pass_id: str,
) -> dict[str, PassVerdict]:
    """Reconstruct PassVerdict dict from loaded sidecar rows."""
    out: dict[str, PassVerdict] = {}
    for qid, row in sidecar.items():
        v = row.get("verdicts", {}) if isinstance(row.get("verdicts"), dict) else {}
        out[qid] = PassVerdict(
            query_id=qid,
            pass_id=pass_id,
            failed=row.get("review_status") == "DISPUTED",
            fail_reason=v.get("fail_reason"),
            answerable=bool(v.get("answerable", False)),
            language_correct=bool(v.get("language_correct", False)),
            query_type_correct=bool(v.get("query_type_correct", False)),
            relevance_correct=bool(v.get("relevance_correct", False)),
            section_correct=bool(v.get("section_correct", False)),
            evidence_sufficient=bool(v.get("evidence_sufficient", False)),
            contamination_risk=str(v.get("contamination_risk", "none")),
            confidence=float(v.get("confidence", 0.0)),
            prompt_hash=str(row.get("review_prompt_hash", "")),
            evidence_refs=tuple((row.get("review_evidence", "") or "").split("|")),
        )
    return out


