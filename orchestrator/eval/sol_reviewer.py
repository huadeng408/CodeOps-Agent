def build_system_prompt(pass_id: str) -> str:
    """Return the system prompt for the given review pass."""
    if pass_id == "B":
        return _SYSTEM_PROMPT_B
    return _SYSTEM_PROMPT_A


def build_user_prompt(
    query: str,
    qrel: dict[str, Any],
    evidence: list[EvidenceChunk],
    pass_id: str,
) -> str:
    """Build the user message with query, qrel fields, and corpus evidence."""
    qrel_fields: list[tuple[str, str]] = [
        ("document_id", str(qrel.get("document_id", ""))),
        ("section_path", json.dumps(qrel.get("section_path", []))),
        ("relevance", str(qrel.get("relevance", ""))),
        ("language", str(qrel.get("language", ""))),
        ("query_type", str(qrel.get("query_type", ""))),
        ("source_id", str(qrel.get("source_id", ""))),
    ]
    if pass_id == "B":
        qrel_fields.reverse()

    qrel_lines = "\n".join(f"  {k}: {v}" for k, v in qrel_fields)

    evidence_chunks = list(evidence)
    if pass_id == "B":
        evidence_chunks = list(reversed(evidence_chunks))

    evidence_lines: list[str] = []
    for i, chunk in enumerate(evidence_chunks, start=1):
        evidence_lines.append(
            f"[{i}] document_id={chunk.document_id}, "
            f"section_path={json.dumps(chunk.section_path)}, "
            f"source_path={chunk.source_path}"
        )
        text = chunk.text[:EVIDENCE_CHUNK_TRUNCATE]
        evidence_lines.append(f"    {text}")

    evidence_block = "\n".join(evidence_lines) if evidence_lines else "(no evidence available)"

    return (
        f"QUERY {qrel.get('query_id', '?')}: {query}\n\n"
        f"QREL:\n{qrel_lines}\n\n"
        f"CORPUS EVIDENCE (use ONLY these numbered fragments):\n{evidence_block}\n\n"
        f"Output ONLY a single JSON object."
    )


def review_prompt_hash(system: str, user: str) -> str:
    """Deterministic prompt hash — sha256 hex, first 16 chars."""
    combined = (system + "\n---USER---\n" + user).encode("utf-8")
    return hashlib.sha256(combined).hexdigest()[:16]


