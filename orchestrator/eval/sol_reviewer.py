from orchestrator.llm.client import ChatRequest, ChatMessage  # noqa: E402
from orchestrator.llm.providers.openai import OpenAIClient  # noqa: E402


async def review_one(
    client: OpenAIClient,
    pass_id: str,
    query: str,
    qrel: dict[str, Any],
    evidence: list[EvidenceChunk],
    model: str,
    revision: str,
) -> PassVerdict:
    """Run one independent review for a single query/qrel pair."""
    qid = str(qrel.get("query_id", "?"))

    # Build prompts
    system = build_system_prompt(pass_id)
    user = build_user_prompt(query, qrel, evidence, pass_id)
    phash = review_prompt_hash(system, user)
    evidence_refs = tuple(
        f"es:{ES_INDEX_DEFAULT}:{c.document_id}:{c.source_path}" for c in evidence
    )

    try:
        response = await client.chat(
            ChatRequest(
                model=model,
                messages=[
                    ChatMessage(role="system", content=system),
                    ChatMessage(role="user", content=user),
                ],
                temperature=0.0,
                thinking_enabled=False,
            )
        )
    except Exception as exc:
        return PassVerdict(
            query_id=qid,
            pass_id=pass_id,
            failed=True,
            fail_reason=f"llm_error:{str(exc)[:200]}",
            answerable=False,
            language_correct=False,
            query_type_correct=False,
            relevance_correct=False,
            section_correct=False,
            evidence_sufficient=False,
            contamination_risk="none",
            confidence=0.0,
            prompt_hash=phash,
            evidence_refs=evidence_refs,
        )

    parsed = parse_verdict_json(response.text)
    if parsed is None:
        return PassVerdict(
            query_id=qid,
            pass_id=pass_id,
            failed=True,
            fail_reason="parse_failed",
            answerable=False,
            language_correct=False,
            query_type_correct=False,
            relevance_correct=False,
            section_correct=False,
            evidence_sufficient=False,
            contamination_risk="none",
            confidence=0.0,
            prompt_hash=phash,
            evidence_refs=evidence_refs,
        )

    verdict = validate_verdict_fields(parsed, qid, pass_id)
    if verdict is None:
        return PassVerdict(
            query_id=qid,
            pass_id=pass_id,
            failed=True,
            fail_reason="validate_failed",
            answerable=False,
            language_correct=False,
            query_type_correct=False,
            relevance_correct=False,
            section_correct=False,
            evidence_sufficient=False,
            contamination_risk="none",
            confidence=0.0,
            prompt_hash=phash,
            evidence_refs=evidence_refs,
        )

    # Attach prompt hash and evidence refs (these are set in caller context)
    return PassVerdict(
        query_id=verdict.query_id,
        pass_id=verdict.pass_id,
        failed=verdict.failed,
        fail_reason=verdict.fail_reason,
        answerable=verdict.answerable,
        language_correct=verdict.language_correct,
        query_type_correct=verdict.query_type_correct,
        relevance_correct=verdict.relevance_correct,
        section_correct=verdict.section_correct,
        evidence_sufficient=verdict.evidence_sufficient,
        contamination_risk=verdict.contamination_risk,
        confidence=verdict.confidence,
        prompt_hash=phash,
        evidence_refs=evidence_refs,
    )


def _verdict_to_row(verdict: PassVerdict, qrel: dict[str, Any], model: str, revision: str) -> dict[str, Any]:
    """Convert a PassVerdict + original qrel into a sidecar JSONL row."""
    now = _review_timestamp()
    row: dict[str, Any] = {
        "query_id": verdict.query_id,
        "document_id": qrel.get("document_id", ""),
        "section_path": qrel.get("section_path", []),
        "relevance": qrel.get("relevance", 0.0),
        "source_id": qrel.get("source_id", ""),
        "language": qrel.get("language", ""),
        "query_type": qrel.get("query_type", ""),
        "review_pass": verdict.pass_id,
        "reviewer_model": model,
        "reviewer_revision": revision,
        "review_prompt_hash": verdict.prompt_hash,
        "review_confidence": verdict.confidence,
        "review_evidence": "|".join(verdict.evidence_refs),
        "review_timestamp": now,
        "verdicts": {
            "answerable": verdict.answerable,
            "language_correct": verdict.language_correct,
            "query_type_correct": verdict.query_type_correct,
            "relevance_correct": verdict.relevance_correct,
            "section_correct": verdict.section_correct,
            "evidence_sufficient": verdict.evidence_sufficient,
            "contamination_risk": verdict.contamination_risk,
            "confidence": verdict.confidence,
        },
    }
    if verdict.failed:
        row["review_status"] = "DISPUTED"
        row["verdicts"]["fail_reason"] = verdict.fail_reason or ""
    else:
        row["review_status"] = "AI_REVIEWED"
    return row


async def run_pass(
    client: OpenAIClient,
    pass_id: str,
    qrels: list[dict[str, Any]],
    queries: dict[str, str],
    es_url: str,
    index: str,
    out_path: str,
    model: str,
    revision: str,
    resume: bool = True,
    max_evidence_chars: int = MAX_EVIDENCE_CHARS_DEFAULT,
) -> dict[str, PassVerdict]:
    """Run all reviews for one pass, writing sidecar rows incrementally."""
    # Determine already-complete query_ids for resume
    completed: set[str] = set()
    if resume:
        completed = set(load_sidecar(out_path))

    # Build ordered worklist
    worklist = list(qrels)
    if pass_id == "B":
        rng = random.Random(PASS_B_SEED)
        rng.shuffle(worklist)

    results: dict[str, PassVerdict] = {}
    for i, qrel in enumerate(worklist):
        qid = str(qrel["query_id"])
        if qid in completed:
            # Recover result from sidecar (best effort)
            sidecar = load_sidecar(out_path)
            row = sidecar.get(qid, {})
            verdicts = row.get("verdicts", {}) if isinstance(row.get("verdicts"), dict) else {}
            rp = PassVerdict(
                query_id=qid,
                pass_id=pass_id,
                failed=row.get("review_status") == "DISPUTED",
                fail_reason=(verdicts.get("fail_reason") if row.get("review_status") == "DISPUTED" else None),
                answerable=bool(verdicts.get("answerable", False)),
                language_correct=bool(verdicts.get("language_correct", False)),
                query_type_correct=bool(verdicts.get("query_type_correct", False)),
                relevance_correct=bool(verdicts.get("relevance_correct", False)),
                section_correct=bool(verdicts.get("section_correct", False)),
                evidence_sufficient=bool(verdicts.get("evidence_sufficient", False)),
                contamination_risk=str(verdicts.get("contamination_risk", "none")),
                confidence=float(verdicts.get("confidence", 0.0)),
                prompt_hash=str(row.get("review_prompt_hash", "")),
                evidence_refs=tuple((row.get("review_evidence", "") or "").split("|")),
            )
            results[qid] = rp
            print(f"[{pass_id}] resume skip {qid} ({i+1}/{len(worklist)})")
            continue

        query_text = queries.get(qid, "")
        if not query_text:
            verdict = PassVerdict(
                query_id=qid,
                pass_id=pass_id,
                failed=True,
                fail_reason="missing_query",
                answerable=False,
                language_correct=False,
                query_type_correct=False,
                relevance_correct=False,
                section_correct=False,
                evidence_sufficient=False,
                contamination_risk="none",
                confidence=0.0,
                prompt_hash="",
                evidence_refs=(),
            )
        else:
            # Fetch evidence
            doc_id = str(qrel.get("document_id", ""))
            section = list(qrel.get("section_path", []) or [])

            try:
                evidence = fetch_evidence(es_url, index, doc_id, section, max_evidence_chars)
            except RuntimeError as exc:
                # Evidence fetch failure → failed pass
                verdict = PassVerdict(
                    query_id=qid,
                    pass_id=pass_id,
                    failed=True,
                    fail_reason="evidence_fetch_failed",
                    answerable=False,
                    language_correct=False,
                    query_type_correct=False,
                    relevance_correct=False,
                    section_correct=False,
                    evidence_sufficient=False,
                    contamination_risk="none",
                    confidence=0.0,
                    prompt_hash="",
                    evidence_refs=(f"es:{index}:{doc_id}",),
                )
                results[qid] = verdict
                row = _verdict_to_row(verdict, qrel, model, revision)
                write_sidecar_row(out_path, row)
                print(f"[{pass_id}] evidence failed {qid} ({i+1}/{len(worklist)}): {exc}")
                continue

            verdict = await review_one(
                client, pass_id, query_text, qrel, evidence, model, revision
            )

        # Overwrite the output file on first write to prevent stale rows
        # from previous runs from accumulating alongside new rows.
        if i == 0 and not resume:
            try:
                with open(out_path, "w", encoding="utf-8") as dummy:
                    dummy.write("")
            except OSError:
                pass

        results[qid] = verdict

        # Append row immediately for crash resilience
        row = _verdict_to_row(verdict, qrel, model, revision)
        write_sidecar_row(out_path, row)

        status = "failed" if verdict.failed else "ok"
        print(
            f"[{pass_id}] {status} {qid} ({i+1}/{len(worklist)}) "
            f"c={verdict.confidence:.2f} r={verdict.relevance_correct}"
        )

    return results


