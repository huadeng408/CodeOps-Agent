def _validate_inputs(
    qrels_path: str, queries_path: str, es_url: str, index: str
) -> tuple[list[dict[str, Any]], dict[str, str]]:
    """Load and cross-validate qrels and queries. Raises ValueError on issues."""
    qrels = load_qrels(qrels_path)
    queries = load_queries(queries_path)

    qrel_ids = {str(r["query_id"]) for r in qrels}
    query_ids = set(queries)

    orphan_qrels = qrel_ids - query_ids
    orphan_queries = query_ids - qrel_ids

    issues: list[str] = []
    if orphan_qrels:
        issues.append(f"qrel query_ids not in queries: {sorted(orphan_qrels)[:10]}...")
    if orphan_queries:
        issues.append(f"query query_ids not in qrels: {sorted(orphan_queries)[:10]}...")

    # Ping ES
    try:
        req = urllib.request.Request(f"{es_url.rstrip('/')}/{index}/_count", method="GET")
        resp = urllib.request.urlopen(req, timeout=5)
        body = json.loads(resp.read().decode("utf-8"))
        count = body.get("count", -1)
        if count <= 0:
            issues.append(f"ES index {index} has count={count}")
    except Exception as exc:
        issues.append(f"ES unreachable: {exc}")

    if issues:
        raise ValueError("Input validation failed:\n  " + "\n  ".join(issues))

    return qrels, queries


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    # Resolve model / revision
    model = args.model or read_env("OPENAI_MODEL")
    if not model:
        print("fatal: --model not set and OPENAI_MODEL not in env", file=sys.stderr)
        return 1
    revision = args.revision or read_env("OPENAI_MODEL_REVISION") or "unknown"

    try:
        qrels, queries = _validate_inputs(
            args.qrels_path, args.queries_path, args.es_url, args.index
        )
    except (ValueError, OSError) as exc:
        print(f"fatal: {exc}", file=sys.stderr)
        return 1

    print(
        f"qrels={len(qrels)} queries={len(queries)} "
        f"es={args.es_url}/{args.index} model={model} revision={revision}"
    )
    if args.dry_run:
        print("dry-run: input validation passed (zero writes, zero LLM calls)")
        return 0

    # Resolve client — must have env vars set
    client = OpenAIClient.from_env()
    if client is None:
        print(
            "fatal: OpenAIClient.from_env() returned None — "
            "set OPENAI_API_KEY / OPENAI_BASE_URL in the environment",
            file=sys.stderr,
        )
        return 1
    client.model = model

    # Ensure output directories exist
    for out_path in (args.pass_a_out, args.pass_b_out, args.arbitrated_out, args.summary_path):
        Path(out_path).parent.mkdir(parents=True, exist_ok=True)

    try:
        run_review(
            qrels_path=args.qrels_path,
            queries_path=args.queries_path,
            pass_a_out=args.pass_a_out,
            pass_b_out=args.pass_b_out,
            arbitrated_out=args.arbitrated_out,
            summary_path=args.summary_path,
            es_url=args.es_url,
            index=args.index,
            model=model,
            revision=revision,
            confidence_threshold=args.confidence_threshold,
            resume=args.resume,
            only=args.only,
            max_evidence_chars=args.max_evidence_chars,
        )
    except RuntimeError as exc:
        print(f"fatal: {exc}", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
