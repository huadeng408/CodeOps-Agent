def load_qrels(path: str | Path) -> list[dict[str, Any]]:
    """Load qrels JSONL; raises ValueError on missing required fields."""
    required = {"query_id", "document_id", "section_path", "relevance", "source_id", "language", "query_type"}
    records: list[dict[str, Any]] = []
    for line_no, line in enumerate(
        Path(path).read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path}:{line_no}: invalid JSON: {exc}") from exc
        if not isinstance(record, dict):
            raise ValueError(f"{path}:{line_no}: expected JSON object")
        missing = required - record.keys()
        if missing:
            raise ValueError(f"{path}:{line_no}: missing required fields: {missing}")
        records.append(record)
    return records


def load_queries(path: str | Path) -> dict[str, str]:
    """Load queries JSONL → {query_id: query_text}."""
    queries: dict[str, str] = {}
    for line_no, line in enumerate(
        Path(path).read_text(encoding="utf-8").splitlines(), start=1
    ):
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise ValueError(f"{path}:{line_no}: invalid JSON: {exc}") from exc
        qid = record.get("query_id")
        text = record.get("query")
        if not qid or not text:
            raise ValueError(f"{path}:{line_no}: must have query_id and query")
        queries[str(qid)] = str(text)
    return queries


def load_sidecar(path: str | Path) -> dict[str, dict[str, Any]]:
    """Load completed rows from a sidecar JSONL for resume.

    Only rows with both *review_timestamp* and a parseable *verdicts* object
    are considered complete (and thus skip-worthy).
    """
    p = Path(path)
    if not p.exists():
        return {}
    completed: dict[str, dict[str, Any]] = {}
    for line_no, line in enumerate(p.read_text(encoding="utf-8").splitlines(), start=1):
        line = line.strip()
        if not line:
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue  # truncated line — not complete
        qid = row.get("query_id")
        ts = row.get("review_timestamp")
        verdicts = row.get("verdicts")
        if qid and ts and isinstance(verdicts, dict):
            completed[str(qid)] = row
    return completed


def write_sidecar_row(path: str | Path, row: dict[str, Any]) -> None:
    """Append one JSON line to a sidecar file (with flush for crash resilience)."""
    text = json.dumps(row, ensure_ascii=False)
    text = redact_text(text)
    with Path(path).open("a", encoding="utf-8") as fh:
        fh.write(text + "\n")
        fh.flush()
        # Also fsync on POSIX for durability; os.fsync is the closest on Windows
        try:
            import os as _os
            _os.fsync(fh.fileno())
        except (AttributeError, OSError):
            pass


